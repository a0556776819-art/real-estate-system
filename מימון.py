class מחלקת_מימון:
    def __init__(self, יתרת_משכנתא_התחלתית, ריבית_שנתית, סך_חודשים):
        self.יתרת_משכנתא = יתרת_משכנתא_התחלתית
        self.ריבית_שנתית = ריבית_שנתית
        self.סך_חודשים = סך_חודשים

    def חשב_החזר_חודשי(self):
        if self.ריבית_שנתית == 0:
            return self.יתרת_משכנתא / self.סך_חודשים
        חודשית = self.ריבית_שנתית / 12
        return self.יתרת_משכנתא * (חודשית * (1 + חודשית)**self.סך_חודשים) / ((1 + חודשית)**self.סך_חודשים - 1)
