class מנהל_תיקי_נדלן:
    def __init__(self, רכישה, מימון, תפעול):
        self.רכישה = רכישה
        self.מימון = מימון
        self.תפעול = תפעול
        self.שווי_נוכחי_מוערך = רכישה.מחיר_דירה

    def חשב_תזרים_חודשי(self):
        return self.תפעול.שכירות_חודשית - (self.מימון.חשב_החזר_חודשי() + (self.תפעול.הוצאות_תחזוקה_שנתיות / 12))

    def חשב_רווח_נקי_על_ההון(self):
        שווי_נטו = self.שווי_נוכחי_מוערך - self.מימון.יתרת_משכנתא
        return שווי_נטו - self.רכישה.הון_עצמי_שהושקע
