import streamlit as st
from רכישה import מחלקת_רכישה
from מימון import מחלקת_מימון
from תפעול import מחלקת_תפעול
from ניהול import מנהל_תיקי_נדלן

st.set_page_config(page_title="ניהול תיקי נדלן", layout="centered")

st.title("מערכת ניהול ובקרת תיקי נדל\"ן")

סיסמה = st.text_input("הכנס סיסמה לכניסה למערכת:", type="password")

if סיסמה == "1234":
    st.success("התחברת בהצלחה!")
    
    st.subheader("הזנת נתוני הנכס")
    מחיר = st.number_input("עלות הדירה (ש\"ח)", value=1500000)
    הון = st.number_input("הון עצמי שהושקע (ש\"ח)", value=500000)
    משכנתא = st.number_input("סכום המשכנתא", value=1000000)
    שכירות = st.number_input("שכירות חודשית", value=5500)
    
    רכישה_בדיקה = מחלקת_רכישה(מחיר, 0, 0, 0, 0, 0, 0, 0, 0, 0, הון)
    מימון_בדיקה = מחלקת_מימון(משכנתא, 0.045, 300)
    תפעול_בדיקה = מחלקת_תפעול(שכירות, 3000)
    
    מנהל = מנהל_תיקי_נדלן(רכישה_בדיקה, מימון_בדיקה, תפעול_בדיקה)
    
    if st.button("חשב דוח נתונים"):
        st.write("---")
        st.metric("תזרים חודשי", f"₪{מנהל.חשב_תזרים_חודשי():,.0f}")
        st.metric("רווח נקי משוער על ההון העצמי", f"₪{מנהל.חשב_רווח_נקי_על_ההון():,.0f}")

elif סיסמה != "":
    st.error("סיסמה שגויה, נסה שנית.")
